/**
 * Prints util/src/cheap_ruler_table.rs: the cosines behind CheapRuler's scale cache. Java's Math.cos is a
 * HotSpot intrinsic whose results differ from fdlibm and from the platform libm in the last bit, so the
 * Rust port embeds the reference values instead of recomputing them.
 */
public final class CheapRulerTable {
  public static void main(String[] args) {
    StringBuilder sb = new StringBuilder();
    sb.append("// Generated by parity/java/data/CheapRulerTable.java from Java's Math.cos; do not edit.\n");
    sb.append("// SCALE_COS[i] = Math.cos(DEG_TO_RAD * ((i * 100000 + 50000) * 1e-6 - 90)) as IEEE bits.\n");
    sb.append("pub(crate) const SCALE_COS: [u64; 1800] = [\n");
    for (int i = 0; i < 1800; i++) {
      int ilat = i * 100000 + 50000;
      double lat = (Math.PI / 180.) * (ilat * 1e-6 - 90);
      if (i % 4 == 0) sb.append("   ");
      sb.append(String.format(" 0x%016x,", Double.doubleToRawLongBits(Math.cos(lat))));
      if (i % 4 == 3) sb.append('\n');
    }
    sb.append("];\n");
    System.out.print(sb);
  }
}
